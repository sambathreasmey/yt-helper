export type TranslationKey = keyof typeof translations.EN;

interface LanguageContextValue {
  language: AppLanguage;
  setLanguage: (language: AppLanguage) => void;
  locale: string;
  t: (key: TranslationKey, values?: Record<string, string | number>) => string;
}

const LanguageContext = createContext<LanguageContextValue | null>(null);

function isAppLanguage(value: string | null): value is AppLanguage {
  return value === "KH" || value === "EN" || value === "CN";
}

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<AppLanguage>("KH");
  const [ready, setReady] = useState(false);

  useEffect(() => {
    try {
      const saved = window.localStorage.getItem(STORAGE_KEY);
      if (isAppLanguage(saved)) setLanguageState(saved);
    } catch {
      // The default language remains available for this session.
    }
    setReady(true);
  }, []);

  useEffect(() => {
    if (!ready) return;
    document.documentElement.lang = language === "KH" ? "km" : language === "CN" ? "zh-CN" : "en";
  }, [language, ready]);

  const setLanguage = useCallback((nextLanguage: AppLanguage) => {
    setLanguageState(nextLanguage);
    try {
      window.localStorage.setItem(STORAGE_KEY, nextLanguage);
    } catch {
      // The language selection remains active for this session.
    }
  }, []);

  const locale = language === "KH" ? "km-KH" : language === "CN" ? "zh-CN" : "en-US";
  const t = useCallback((key: TranslationKey, values: Record<string, string | number> = {}) => {
    let text: string = translations[language][key];
    for (const [name, value] of Object.entries(values)) {
      text = text.replaceAll(`{${name}}`, String(value));
    }
    return text;
  }, [language]);

  const value = useMemo(
    () => ({ language, setLanguage, locale, t }),
    [language, setLanguage, locale, t],
  );
  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage(): LanguageContextValue {
  const context = useContext(LanguageContext);
  if (!context) throw new Error("useLanguage must be used inside LanguageProvider.");
  return context;
}
